import { makeWps, makeLubes } from './utils';

interface MatrixSeed {
  id: string;
  category: string;
  durationGroup: 'short' | 'medium' | 'long';
  durationMin: number;
  intensity: 'soft' | 'medium' | 'intense';
  icon: string;
  title: string;
  desc: string;
  minRange: [number, number];
  maxRange: [number, number];
  spmRange: [number, number];
  hardnessRange: [number, number];
  wavePattern: 'sine_swell' | 'crescendo' | 'tease_drop' | 'deep_hold' | 'flutter_pulse' | 'trance_loop' | 'golden_climax' | 'power_surge' | 'extreme_burst' | 'poly_experiment';
}

function buildMultiPhasePreset(seed: MatrixSeed): PresetDefinition {
  const durationMs = seed.durationMin * 60 * 1000;
  const steps = seed.durationGroup === 'short' ? 12 : seed.durationGroup === 'medium' ? 18 : 24;
  const dt = Math.round(durationMs / steps);

  const minPts: { time: number; pos: number }[] = [];
  const maxPts: { time: number; pos: number }[] = [];
  const spmPts: { time: number; pos: number }[] = [];
  const hrdPts: { time: number; pos: number }[] = [];

  const [minLo, minHi] = seed.minRange;
  const [maxLo, maxHi] = seed.maxRange;
  const [spmLo, spmHi] = seed.spmRange;
  const [hrdLo, hrdHi] = seed.hardnessRange;

  for (let i = 0; i <= steps; i++) {
    const t = i === steps ? durationMs : i * dt;
    const p = i / steps; // 0..1 progress
    const env = Math.sin(p * Math.PI); // 0 -> 1 -> 0 arch
    const waveA = 0.5 + 0.5 * Math.sin(p * Math.PI * (seed.durationGroup === 'long' ? 8 : 4));
    const waveB = 0.5 + 0.5 * Math.cos(p * Math.PI * 6);

    let minPos = minLo + (minHi - minLo) * (1 - env * 0.7);
    let maxPos = maxLo + (maxHi - maxLo) * (0.35 + 0.65 * env);
    let spmPos = spmLo + (spmHi - spmLo) * (0.25 + 0.75 * env * waveA);
    let hrdPos = hrdLo + (hrdHi - hrdLo) * (0.3 + 0.7 * env);

    switch (seed.wavePattern) {
      case 'sine_swell':
        minPos = minLo + (minHi - minLo) * waveB;
        maxPos = maxLo + (maxHi - maxLo) * (0.4 + 0.6 * waveA);
        spmPos = spmLo + (spmHi - spmLo) * (0.35 + 0.65 * env * waveA);
        break;
      case 'crescendo': {
        const ramp = p < 0.82 ? Math.pow(p / 0.82, 1.35) : 1 - ((p - 0.82) / 0.18) * 0.75;
        minPos = minHi - (minHi - minLo) * ramp;
        maxPos = maxLo + (maxHi - maxLo) * ramp;
        spmPos = spmLo + (spmHi - spmLo) * ramp;
        hrdPos = hrdLo + (hrdHi - hrdLo) * ramp;
        break;
      }
      case 'tease_drop': {
        const isDrop = i > 0 && i < steps && i % 3 === 0;
        minPos = isDrop ? minHi : minLo;
        maxPos = isDrop ? minHi + 18 : maxLo + (maxHi - maxLo) * env;
        spmPos = isDrop ? Math.max(12, spmLo * 0.6) : spmLo + (spmHi - spmLo) * (0.5 + 0.5 * waveA);
        hrdPos = isDrop ? hrdLo : hrdLo + (hrdHi - hrdLo) * waveA;
        break;
      }
      case 'deep_hold':
        minPos = minLo + (minHi - minLo) * (0.2 + 0.8 * waveB * 0.5);
        maxPos = maxHi - (maxHi - maxLo) * (1 - env) * 0.4;
        spmPos = spmLo + (spmHi - spmLo) * (0.3 + 0.7 * waveA);
        break;
      case 'flutter_pulse':
        minPos = minLo + (minHi - minLo) * (0.4 + 0.6 * env);
        maxPos = Math.min(96, minPos + 16 + (maxHi - maxLo) * 0.35 * waveA);
        spmPos = spmLo + (spmHi - spmLo) * (0.45 + 0.55 * waveA);
        break;
      case 'trance_loop':
        minPos = minLo + (minHi - minLo) * 0.5 * waveB;
        maxPos = maxLo + (maxHi - maxLo) * (0.65 + 0.35 * waveA);
        spmPos = spmLo + (spmHi - spmLo) * (0.5 + 0.35 * Math.sin(p * Math.PI * 2));
        break;
      case 'golden_climax': {
        const phiP = p <= 0.618 ? Math.pow(p / 0.618, 1.5) : 0.45 + 0.55 * Math.sin(((p - 0.618) / 0.382) * Math.PI);
        maxPos = maxLo + (maxHi - maxLo) * phiP;
        spmPos = spmLo + (spmHi - spmLo) * phiP;
        hrdPos = hrdLo + (hrdHi - hrdLo) * phiP;
        break;
      }
      case 'power_surge':
        minPos = i % 2 === 0 ? minLo : minHi * 0.7;
        maxPos = maxLo + (maxHi - maxLo) * (0.55 + 0.45 * env);
        spmPos = spmLo + (spmHi - spmLo) * (i % 2 === 0 ? 0.9 : 0.55) * (0.5 + 0.5 * env);
        break;
      case 'extreme_burst':
        minPos = minLo;
        maxPos = maxLo + (maxHi - maxLo) * (i % 2 === 0 ? 1 : 0.7);
        spmPos = spmLo + (spmHi - spmLo) * (0.6 + 0.4 * waveA);
        hrdPos = hrdLo + (hrdHi - hrdLo) * (0.7 + 0.3 * env);
        break;
      case 'poly_experiment':
        minPos = minLo + (minHi - minLo) * Math.abs(Math.sin(i * 1.7));
        maxPos = Math.max(minPos + 16, maxLo + (maxHi - maxLo) * Math.abs(Math.cos(i * 1.1)));
        spmPos = spmLo + (spmHi - spmLo) * Math.abs(Math.sin(i * 2.3));
        hrdPos = hrdLo + (hrdHi - hrdLo) * Math.abs(Math.cos(i * 1.5));
        break;
    }

    if (i === 0 || i === steps) {
      minPos = minLo;
      maxPos = Math.max(minLo + 20, maxLo);
      spmPos = spmLo;
      hrdPos = hrdLo;
    }

    minPts.push({ time: t, pos: Math.round(minPos) });
    maxPts.push({ time: t, pos: Math.round(Math.max(minPos + 15, maxPos)) });
    spmPts.push({ time: t, pos: Math.round(spmPos) });
    hrdPts.push({ time: t, pos: Math.round(hrdPos) });
  }

  const q1 = Math.round(durationMs * 0.25);
  const q2 = Math.round(durationMs * 0.6);
  const q3 = Math.round(durationMs * 0.85);

  const subsections: Subsection[] = [
    { id: `${seed.id}-s1`, name: '1. Einstimmung & Ankommen', startTime: 0, endTime: q1 },
    { id: `${seed.id}-s2`, name: '2. Sinnliche Entfaltung', startTime: q1, endTime: q2 },
    { id: `${seed.id}-s3`, name: '3. Hauptwelle & Fokus', startTime: q2, endTime: q3 },
    { id: `${seed.id}-s4`, name: '4. Nachklang & Ausgleiten', startTime: q3, endTime: durationMs },
  ];

  const lubeTriggers: LubeTrigger[] = makeLubes([
    { time: Math.round(durationMs * 0.15), bursts: 1 },
    { time: Math.round(durationMs * 0.5), bursts: seed.intensity === 'intense' ? 2 : 1 },
    ...(seed.durationGroup === 'long'
      ? [{ time: Math.round(durationMs * 0.78), bursts: 2 }]
      : []),
  ]);

  const colorMap: Record<string, string> = {
    soft: 'cyan',
    medium: 'purple',
    intense: 'rose',
  };

  return {
    id: seed.id,
    icon: seed.icon,
    durationGroup: seed.durationGroup,
    duration: `${seed.durationMin} Min`,
    category: seed.category,
    intensity: seed.intensity,
    title: seed.title,
    desc: seed.desc,
    specs: `${seed.spmRange[0]}–${seed.spmRange[1]} SPM | ${seed.minRange[0]}–${seed.maxRange[1]}% Hub`,
    color: colorMap[seed.intensity] || 'cyan',
    durationMs,
    waypointsMinDepth: makeWps(minPts, 'min'),
    waypointsMaxDepth: makeWps(maxPts, 'max'),
    waypointsSpm: makeWps(spmPts, 'spm'),
    waypointsHardness: makeWps(hrdPts, 'hrd'),
    lubeTriggers,
    subsections,
    recommendedSmoothness:
      seed.intensity === 'soft' ? 9 : seed.intensity === 'medium' ? 5 : 2,
  };
}

